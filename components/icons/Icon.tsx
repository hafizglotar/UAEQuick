export type IconName = keyof typeof icons;

export function Icon({
  name,
  label,
  size = 20,
  className,
  ...rest
}: { name: IconName; label?: string } & Omit<LucideProps, 'ref'>) {
  const Cmp = icons[name];
  return (
    <Cmp
      size={size}
      className={className}
      aria-hidden={label ? undefined : true}
      aria-label={label}
      role={label ? 'img' : undefined}
      focusable="false"
      {...rest}
    />
  );
}
